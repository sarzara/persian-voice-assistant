# Quality signals per run, derived from data the system already records. Read by the dashboard.
#   decision        what the owner did with a proposal: confirmed / edited / cancelled / expired / pending
#   json_failures   final answers rejected because the model's JSON was invalid (schema or not JSON)
#   guardrail_rejections  valid answers refused by code guardrails (invented address, past date, ...)
#   tool_failures   failed read-tool calls during planning
#   retries         extra LLM HTTP attempts + admin/API retries of the run
RUN_QUALITY_VIEW = """
CREATE VIEW run_quality AS
SELECT
    r.id AS run_id, r.user_id, r.created_at, r.model, r.intent, r.status, r.steps, r.error,
    r.prompt_tokens, r.completion_tokens, r.latency_ms,
    CASE
        WHEN r.intent NOT IN ('schedule', 'email') OR r.action_json IS NULL THEN NULL
        WHEN r.status IN ('confirmed', 'executed') OR tc.exec_attempts > 0 THEN 'confirmed'
        WHEN r.error IN ('edit_requested', 'edit_consumed') THEN 'edited'
        WHEN r.error = 'cancelled' THEN 'cancelled'
        WHEN r.error = 'expired' THEN 'expired'
        WHEN r.status = 'pending_confirmation' THEN 'pending'
    END AS decision,
    (r.status = 'needs_clarification') AS asked_question,
    COALESCE(tc.terminal_calls, 0) AS terminal_calls,
    COALESCE(tc.json_failures, 0) AS json_failures,
    COALESCE(tc.guardrail_rejections, 0) AS guardrail_rejections,
    COALESCE(tc.tool_calls, 0) AS tool_calls,
    COALESCE(tc.tool_failures, 0) AS tool_failures,
    tc.exec_ok,
    COALESCE(lc.llm_calls, 0) AS llm_calls,
    COALESCE(lc.tokens, 0) AS tokens,
    lc.cost_usd,
    COALESCE(lc.llm_retries, 0) + COALESCE(ar.api_retries, 0) AS retries,
    fb.rating
FROM agent_runs r
LEFT JOIN LATERAL (
    SELECT
        count(*) FILTER (WHERE t.tool_name LIKE 'submit_%' OR t.tool_name = 'ask_user') AS terminal_calls,
        count(*) FILTER (WHERE t.tool_name LIKE 'submit_%' AND t.status = 'failed'
                         AND COALESCE(t.result_json->>'kind', 'schema') IN ('schema', 'json')) AS json_failures,
        count(*) FILTER (WHERE t.tool_name LIKE 'submit_%' AND t.result_json->>'kind' = 'guardrail') AS guardrail_rejections,
        count(*) FILTER (WHERE t.tool_name IN ('get_current_datetime', 'convert_jalali_date', 'find_contact',
                                               'list_calendar_events')) AS tool_calls,
        count(*) FILTER (WHERE t.tool_name IN ('get_current_datetime', 'convert_jalali_date', 'find_contact',
                                               'list_calendar_events') AND t.status = 'failed') AS tool_failures,
        count(*) FILTER (WHERE t.idempotency_key LIKE 'run-%-execute%') AS exec_attempts,
        bool_or(t.status = 'succeeded') FILTER (WHERE t.idempotency_key LIKE 'run-%-execute%'
                                                OR t.idempotency_key LIKE 'mcp-%') AS exec_ok
    FROM tool_calls t WHERE t.run_id = r.id
) tc ON true
LEFT JOIN LATERAL (
    SELECT count(*) AS llm_calls, sum(l.prompt_tokens + l.completion_tokens) AS tokens,
           sum(l.cost_usd) AS cost_usd, sum(l.attempts - 1) AS llm_retries
    FROM llm_calls l WHERE l.run_id = r.id
) lc ON true
LEFT JOIN LATERAL (
    SELECT count(*) AS api_retries FROM audit_events a
    WHERE a.event_type = 'run.retry' AND a.payload_json->>'run_id' = r.id::text
) ar ON true
LEFT JOIN run_feedback fb ON fb.run_id = r.id
"""


